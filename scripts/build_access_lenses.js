/**
 * Write one access lens per transport mode (lenses/access-<mode>.css) from the
 * configuration in config/access_lens.js. Run through `npm run build:lenses`.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import {
    ACCESS_LENS_BUCKET_COLORS,
    ACCESS_LENS_KEY_PREFIX,
    ACCESS_LENS_MISSING_BUCKET,
    ACCESS_LENS_MODES,
    ACCESS_LENS_OTHER_BUCKET
} from '../config/access_lens.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Features kept visible although they are not highways: the unsaved edits and the selection. */
const KEPT = ':not(.added):not(.retagged):not(.geometry-edited):not(.selected):not(.selected-member)';
const KEPT_NODES = ':not(.added):not(.moved):not(.retagged):not(.selected):not(.selected-member)';

/** Rules shared by every access lens: only the highway ways stay visible. */
const HIGHWAYS_ONLY = `/* --- hide saved features except highway ways --- */

.layer-osm path.area.fill${KEPT},
.layer-osm path.area.stroke${KEPT},
.layer-osm path.area.shadow${KEPT} {
    display: none !important;
}

.layer-osm g.vertex${KEPT_NODES}:not(.sibling) {
    display: none !important;
}

.layer-osm g.point:not([class*="tag-highway"])${KEPT_NODES} {
    display: none !important;
}

.layer-osm path.line.shadow:not([class*="tag-highway"])${KEPT},
.layer-osm path.line.casing:not([class*="tag-highway"])${KEPT},
.layer-osm path.line.stroke:not([class*="tag-highway"])${KEPT},
.layer-osm path.line.over-stroke:not([class*="tag-highway"])${KEPT} {
    display: none !important;
}

/* --- highways: one solid stroke, no casing and no over-stroke --- */

.layer-osm path.line.casing[class*="tag-highway"],
.layer-osm path.line.over-stroke[class*="tag-highway"] {
    stroke: none !important;
    opacity: 0 !important;
}

.layer-osm path.line.stroke[class*="tag-highway"] {
    stroke: ${ACCESS_LENS_BUCKET_COLORS[ACCESS_LENS_OTHER_BUCKET]} !important;
    stroke-dasharray: none !important;
    opacity: 1 !important;
}
`;

/**
 * @param {{ id: string, keys: string[] }} mode - one of ACCESS_LENS_MODES
 * @returns {string} the CSS of the access lens of the mode
 */
function accessLensCss(mode) {
    const classPrefix = `tag-${ACCESS_LENS_KEY_PREFIX}${mode.id}-`;
    const buckets = Object.keys(ACCESS_LENS_BUCKET_COLORS);
    const legend = buckets.map((bucket) => ` *   ${bucket} ${ACCESS_LENS_BUCKET_COLORS[bucket]}`).join('\n');
    const bucketRules = buckets.map((bucket) =>
        `.layer-osm path.line.stroke.${classPrefix}${bucket} {\n    stroke: ${ACCESS_LENS_BUCKET_COLORS[bucket]} !important;\n}`
    ).join('\n');

    return `/* ============================================================================
 * Lens — access for ${mode.id}
 * ----------------------------------------------------------------------------
 * Generated by scripts/build_access_lenses.js from config/access_lens.js — do
 * not edit. Only highway ways are shown, colored by their effective access for
 * ${mode.id}: the first tag among ${mode.keys.join(', ')}, else the default of the
 * highway type. Not every color applies to every mode.
 *
${legend}
 * ============================================================================ */

${HIGHWAYS_ONLY}
/* --- effective access for ${mode.id} --- */

${bucketRules}

/* access to tag: short dashes on a black casing, like the missing tag highlights of lenses/quebec-validation.css */
.layer-osm path.line.stroke.${classPrefix}${ACCESS_LENS_MISSING_BUCKET} {
    stroke-dasharray: 2, 2 !important;
    stroke-linecap: butt !important;
}
.layer-osm path.line.casing.${classPrefix}${ACCESS_LENS_MISSING_BUCKET} {
    stroke: #000 !important;
    opacity: 1 !important;
}
`;
}

for (const mode of ACCESS_LENS_MODES) {
    const file = path.join(ROOT, 'lenses', `access-${mode.id.replace(/_/g, '-')}.css`);
    fs.writeFileSync(file, accessLensCss(mode));
}
